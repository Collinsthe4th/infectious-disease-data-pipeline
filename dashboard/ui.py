"""Shared page furniture: config, synthetic-data banner, disease/location pickers."""

from __future__ import annotations

import streamlit as st

import data

COLOURS = {"observed": "#1f4e79", "trend": "#c0392b", "forecast": "#e67e22", "alert": "#c0392b", "band": "rgba(230,126,34,0.18)"}


def rounded(df, decimals: int = 2):
    """Round numeric columns only (dates and text are left untouched)."""
    num = df.select_dtypes("number").columns
    return df.assign(**{c: df[c].round(decimals) for c in num})


def page(title: str, icon: str = "🦠") -> None:
    st.set_page_config(page_title=f"{title} · NG Disease Surveillance", page_icon=icon, layout="wide")
    st.title(title)
    try:
        if data.has_synthetic():
            st.warning("This database contains **SYNTHETIC demo data** generated by the project, not real NCDC "
                       "figures. Use it to explore the system only; do not cite these numbers.", icon="⚠️")
    except Exception as exc:  # database not reachable
        st.error(f"Cannot reach the database: {exc}")
        st.info("Start it with `docker compose up -d db` and load data with `docker compose run --rm app demo`.")
        st.stop()


def disease_picker(key: str = "disease", default: str = "LASSA") -> tuple[str, str]:
    ds = data.diseases()
    names = ds["disease_name"].tolist()
    codes = ds["disease_code"].tolist()
    idx = codes.index(default) if default in codes else 0
    name = st.sidebar.selectbox("Disease", names, index=idx, key=key)
    return codes[names.index(name)], name


def location_picker(disease_code: str, key: str = "location") -> tuple[str | None, str | None]:
    locs = data.locations_with_data(disease_code)
    if locs.empty:
        st.info("No data loaded for this disease yet.")
        return None, None
    labels = [("Nigeria (national)" if lvl == 0 else name) for name, lvl in zip(locs["location_name"], locs["admin_level"])]
    choice = st.sidebar.selectbox("Location", labels, key=key)
    row = locs.iloc[labels.index(choice)]
    return row["pcode"], choice
